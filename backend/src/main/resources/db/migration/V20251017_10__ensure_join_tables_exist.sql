-- =============================
-- AGENTE_COMARCA
-- =============================
DECLARE v INTEGER; v_agv INTEGER; v_com INTEGER; BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='AGENTE_COMARCA';
  IF v = 0 THEN
    -- If parent tables exist, create with FKs; otherwise create without FKs now
    SELECT COUNT(*) INTO v_agv FROM user_tables WHERE table_name='AGENTE_VOLUNTARIO';
    SELECT COUNT(*) INTO v_com FROM user_tables WHERE table_name='COMARCA';
    IF v_agv > 0 AND v_com > 0 THEN
      EXECUTE IMMEDIATE q'[
        CREATE TABLE AGENTE_COMARCA (
          ID         NUMBER(19) PRIMARY KEY,
          AGENTE_ID  NUMBER(19) NOT NULL,
          COMARCA_ID NUMBER(19) NOT NULL,
          CONSTRAINT UK_AGCO01 UNIQUE (AGENTE_ID, COMARCA_ID),
          CONSTRAINT FK_AGCO_AGVO01 FOREIGN KEY (AGENTE_ID)  REFERENCES AGENTE_VOLUNTARIO(ID),
          CONSTRAINT FK_AGCO_COMA01 FOREIGN KEY (COMARCA_ID) REFERENCES COMARCA(ID)
        )
      ]';
    ELSE
      EXECUTE IMMEDIATE q'[
        CREATE TABLE AGENTE_COMARCA (
          ID         NUMBER(19) PRIMARY KEY,
          AGENTE_ID  NUMBER(19) NOT NULL,
          COMARCA_ID NUMBER(19) NOT NULL,
          CONSTRAINT UK_AGCO01 UNIQUE (AGENTE_ID, COMARCA_ID)
        )
      ]';
    END IF;
  END IF;
END;
/

BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE S_AGENTE_COMARCA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN NULL; END;
