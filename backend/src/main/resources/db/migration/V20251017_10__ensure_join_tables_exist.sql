-- Backfill IDs if table exists and rows have NULL ID
DECLARE v_tbl NUMBER; v_has NUMBER; BEGIN
  SELECT COUNT(*) INTO v_tbl FROM user_tables WHERE table_name='AGENTE_COMARCA';
  IF v_tbl > 0 THEN
    BEGIN EXECUTE IMMEDIATE 'UPDATE AGENTE_COMARCA SET ID = S_AGENTE_COMARCA.NEXTVAL WHERE ID IS NULL'; EXCEPTION WHEN OTHERS THEN NULL; END;
  END IF;
END;
/

-- Trigger to auto-populate ID
DECLARE v_tbl NUMBER; BEGIN
  SELECT COUNT(*) INTO v_tbl FROM user_tables WHERE table_name='AGENTE_COMARCA';
  IF v_tbl > 0 THEN
    BEGIN EXECUTE IMMEDIATE 'DROP TRIGGER TR_BIR_AGC01'; EXCEPTION WHEN OTHERS THEN NULL; END;
    EXECUTE IMMEDIATE q'[CREATE OR REPLACE TRIGGER TR_BIR_AGC01
      BEFORE INSERT ON AGENTE_COMARCA
      FOR EACH ROW
      BEGIN
        IF :NEW.ID IS NULL THEN :NEW.ID := S_AGENTE_COMARCA.NEXTVAL; END IF;
      END;]';
  END IF;
END;
/

